/**
 * Generates `src/engine/skills.gen.ts` from the framework skills in
 * `../skills/`.
 *
 * Usage:
 *   bun run embed            # rewrites the generated module
 *   bun run embed -- --check # exits with 1 when the module is stale
 *
 * The generated module imports every file of the skills tree (except
 * `tests/` and caches) as text, so `bun build --compile` carries the
 * scripts, templates and rules inside the binary. The engine materializes
 * this tree on disk before running a script, keeping the relative paths
 * the scripts expect (`../../templates`, sibling imports).
 */
import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { join, relative } from "node:path";

const cliRoot = join(import.meta.dir, "..");
const skillsRoot = join(cliRoot, "..", "skills");
const target = join(cliRoot, "src", "engine", "skills.gen.ts");
const skipped = new Set(["tests", "__pycache__", "node_modules", ".DS_Store"]);

/** Lists the files of the skills tree in a stable order. */
function walk(directory: string): string[] {
  const files: string[] = [];
  for (const name of readdirSync(directory).sort()) {
    if (skipped.has(name)) continue;
    const path = join(directory, name);
    if (statSync(path).isDirectory()) files.push(...walk(path));
    else files.push(path);
  }
  return files;
}

const files = walk(skillsRoot);
const lines = [
  "/**",
  " * Generated by scripts/embed-skills.ts. Do not edit by hand.",
  " *",
  " * Every file of the framework skills tree, imported as text so the",
  " * compiled binary carries the scripts, templates and rules.",
  " */",
];
files.forEach((file, index) => {
  const from = relative(join(cliRoot, "src", "engine"), file).split("\\").join("/");
  lines.push(`import f${index} from ${JSON.stringify(from)} with { type: "text" };`);
});
lines.push("", "/** Relative path inside `skills/` mapped to the file contents. */");
lines.push("export const SKILL_FILES: Readonly<Record<string, string>> = {");
files.forEach((file, index) => {
  lines.push(`  ${JSON.stringify(relative(skillsRoot, file).split("\\").join("/"))}: f${index},`);
});
lines.push("};", "");
const content = lines.join("\n");

if (process.argv.includes("--check")) {
  let current = "";
  try { current = readFileSync(target, "utf8"); } catch { /* missing counts as stale */ }
  if (current !== content) {
    console.error("src/engine/skills.gen.ts is stale. Run: bun run embed");
    process.exit(1);
  }
  console.log(`✓ src/engine/skills.gen.ts (${files.length} files)`);
} else {
  writeFileSync(target, content);
  console.log(`✓ src/engine/skills.gen.ts (${files.length} files)`);
}
