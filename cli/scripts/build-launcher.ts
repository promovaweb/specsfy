/**
 * Generates `bin/specsfy`, the launcher served by `get.specsfy.dev`, from the
 * npm wrapper `npm/bin/specsfy.cjs`.
 *
 * Usage:
 *   bun run launcher            # rewrites bin/specsfy
 *   bun run launcher -- --check # exits with 1 when bin/specsfy is stale
 *
 * The launcher is a single Node.js file, like the executable that
 * `get.specsfy.dev` served before the Bun rewrite, so existing installs and
 * their `upgrade` keep working. Inside a checkout (with `../src/main.ts`) it
 * runs the sources with Bun, which the framework's own tests rely on.
 * Downloaded alone, it fetches the release binary of its version, checks
 * the SHA256SUMS and runs it with `SPECSFY_LAUNCHER` pointing to itself, so
 * `specsfy upgrade` replaces the launcher instead of the cached binary.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const cli = join(import.meta.dir, "..");
const target = join(cli, "bin", "specsfy");
const { version } = JSON.parse(readFileSync(join(cli, "package.json"), "utf8")) as { version: string };
let source = readFileSync(join(cli, "npm", "bin", "specsfy.cjs"), "utf8");

/** Replaces one exact fragment, failing loudly when the wrapper changed shape. */
function swap(from: string, to: string): void {
  if (!source.includes(from)) throw new Error(`npm/bin/specsfy.cjs no longer contains: ${from}`);
  source = source.replace(from, to);
}

swap(`const { version } = require("../package.json");`, `const version = ${JSON.stringify(version)};`);
swap(
  `env: { ...process.env, SPECSFY_NPM_WRAPPER: "1", SPECSFY_NPM_SCOPE: installScope() },`,
  `env: { ...process.env, SPECSFY_LAUNCHER: __filename },`,
);
swap("`specsfy-npm/${version}`", "`specsfy-launcher/${version}`");
swap(
  `async function main() {\n`,
  `async function main() {
  // Inside a checkout, run the Bun sources (framework tests, development).
  const sources = path.join(__dirname, "..", "src", "main.ts");
  if (fs.existsSync(sources) && !process.env.SPECSFY_BINARY) {
    const run = require("node:child_process").spawnSync(process.env.BUN_BINARY || "bun", [sources, ...process.argv.slice(2)], { stdio: "inherit" });
    if (!run.error) process.exit(run.status === null ? 1 : run.status);
    if (run.error.code !== "ENOENT") {
      process.stderr.write(\`specsfy: cannot run Bun: \${run.error.message}\\n\`);
      process.exit(1);
    }
  }
`,
);
const header = `#!/usr/bin/env node
/*
 * Generated by cli/scripts/build-launcher.ts from cli/npm/bin/specsfy.cjs.
 * Do not edit by hand: run \`bun run launcher\` in cli/.
 */
`;
source = header + source.replace(/^#!.*\n/, "");

if (process.argv.includes("--check")) {
  let current = "";
  try { current = readFileSync(target, "utf8"); } catch { /* missing counts as stale */ }
  if (current !== source) {
    console.error("bin/specsfy is stale. Run: bun run launcher");
    process.exit(1);
  }
  console.log(`✓ bin/specsfy (launcher v${version})`);
} else {
  writeFileSync(target, source, { mode: 0o755 });
  console.log(`✓ bin/specsfy (launcher v${version})`);
}
