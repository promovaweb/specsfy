/**
 * Runs the framework scripts embedded in the binary.
 *
 * The skills tree (`skills.gen.ts`) is written once per version to
 * `~/.specsfy/runtime/<version>-<digest>/skills/`, keeping the layout the
 * scripts expect. Each run spawns the binary itself with `BUN_BE_BUN=1`, so
 * the compiled executable behaves as the Bun runtime and executes the
 * `.mjs` file: no Node.js is needed on the machine. In development,
 * `process.execPath` is already `bun` and the variable is harmless.
 *
 * Some scripts (`verify_repo`, `validate_tasks`) spawn `node` themselves.
 * When `node` is not on the PATH, or when `nodeShim: "always"` asks for it,
 * `runScript` prepends a directory with a `node` shim that re-executes the
 * binary as Bun (see `ensureNodeShim`), so grandchildren work as well.
 *
 * Callers receive stdout, stderr, the exit code and, when the script prints
 * JSON, the parsed value. A script that exits with a non-zero code is not an
 * exception here: the command decides how to map it.
 */
import { createHash } from "node:crypto";
import { copyFileSync, existsSync, linkSync, mkdirSync, readFileSync, renameSync, writeFileSync } from "node:fs";
import { delimiter, dirname, join } from "node:path";
import { manifest } from "../app/manifest.ts";
import { error } from "../app/errors.ts";
import { baseDir, ensureBaseDir } from "../config/paths.ts";
import { SKILL_FILES } from "./skills.gen.ts";

/** Result of one script execution. */
export interface ScriptRun {
  /** Script path inside the skills tree, e.g. `specsfy-04-validate/scripts/validate_spec.mjs`. */
  script: string;
  args: string[];
  code: number;
  stdout: string;
  stderr: string;
  /** Parsed stdout when it is a JSON document. */
  json?: unknown;
}

let cachedRoot: string | undefined;

/** Short digest of the embedded tree, so a new build never reuses stale files. */
function treeDigest(): string {
  const hash = createHash("sha256");
  for (const [path, content] of Object.entries(SKILL_FILES)) hash.update(path).update("\0").update(content).update("\0");
  return hash.digest("hex").slice(0, 12);
}

/**
 * Writes the embedded skills tree to disk when needed and returns the
 * directory that mirrors `skills/`. `SPECSFY_SKILLS_DIR` points to an
 * existing tree instead, used by the framework's own tests.
 */
export function skillsRuntimeDir(): string {
  const override = process.env.SPECSFY_SKILLS_DIR;
  if (override && override.trim() !== "") return override;
  // Reuse the cached tree only while it still exists (tests and cleanups may remove the data directory).
  if (cachedRoot && cachedRoot.startsWith(baseDir()) && existsSync(join(cachedRoot, ".complete"))) return cachedRoot;
  const root = join(baseDir(), "runtime", `${manifest.version}-${treeDigest()}`, "skills");
  const marker = join(root, ".complete");
  if (!existsSync(marker)) {
    ensureBaseDir();
    for (const [path, content] of Object.entries(SKILL_FILES)) {
      const target = join(root, path);
      mkdirSync(dirname(target), { recursive: true });
      writeFileSync(target, content, { mode: path.endsWith(".mjs") ? 0o755 : 0o644 });
    }
    writeFileSync(marker, `${new Date().toISOString()}\n`);
  }
  cachedRoot = root;
  return root;
}

/** Lists the embedded scripts as `skill/scripts/file.mjs`. */
export function embeddedScripts(): string[] {
  return Object.keys(SKILL_FILES).filter((path) => /\/scripts\/[^/]+\.mjs$/.test(path)).sort();
}

/** Options of `runScript`. */
export interface RunOptions {
  /** Working directory of the script. Defaults to the current directory. */
  cwd?: string;
  /** Extra environment variables. */
  env?: Record<string, string>;
  /** Text written to the script's stdin. */
  input?: string;
  /**
   * Whether to put a `node` shim at the start of the PATH, for scripts that
   * spawn `node`. `auto` (default) adds it only when no `node` is found on
   * the PATH; `always` adds it even when Node.js exists, which also enables
   * the `.agents/skills` fallback of the shim; `never` leaves the PATH alone.
   */
  nodeShim?: NodeShimMode;
}

/** Modes of `RunOptions.nodeShim`. */
export type NodeShimMode = "auto" | "always" | "never";

/** Quotes a value for a POSIX shell. */
function shellQuote(value: string): string {
  return "'" + value.split("'").join("'\\''") + "'";
}

/** Writes a file atomically when its content differs. */
function writeIfChanged(path: string, content: string, mode: number): void {
  if (existsSync(path) && readFileSync(path, "utf8") === content) return;
  const temporary = `${path}.${process.pid}.tmp`;
  writeFileSync(temporary, content, { mode });
  renameSync(temporary, path);
}

/** POSIX shim body. `$1` under `.agents/skills/` falls back to `SPECSFY_SKILLS_DIR`. */
const POSIX_SHIM_BODY = [
  "#!/bin/sh",
  "# Generated by specsfy: runs Node.js scripts with the Specsfy binary acting as Bun.",
  'if [ "$#" -gt 0 ] && [ -n "$SPECSFY_SKILLS_DIR" ] && [ ! -e "$1" ]; then',
  '  case "$1" in',
  "    */.agents/skills/*)",
  '      fallback="$SPECSFY_SKILLS_DIR/${1#*/.agents/skills/}"',
  '      if [ -e "$fallback" ]; then shift; set -- "$fallback" "$@"; fi',
  "      ;;",
  "  esac",
  "fi",
];

/**
 * Creates (once per executable) a directory holding a `node` command that
 * runs `process.execPath` with `BUN_BE_BUN=1`, and returns that directory.
 *
 * On POSIX the shim is a `sh` script. When its first argument is a script
 * under `<dir>/.agents/skills/` that does not exist and `SPECSFY_SKILLS_DIR`
 * is set, it runs the file with the same relative path from that directory
 * instead, so projects whose skills live in another agent folder still get
 * the checks of `verify_repo`. On Windows the shim is a hard link (or copy)
 * of the binary named `node.exe`; `BUN_BE_BUN=1` reaches it through the
 * inherited environment and there is no path fallback.
 */
export function ensureNodeShim(): string {
  const digest = createHash("sha256").update(process.execPath).digest("hex").slice(0, 12);
  const dir = join(baseDir(), "runtime", "node-shim", digest);
  ensureBaseDir();
  mkdirSync(dir, { recursive: true });
  if (process.platform === "win32") {
    const target = join(dir, "node.exe");
    if (!existsSync(target)) {
      try { linkSync(process.execPath, target); } catch { copyFileSync(process.execPath, target); }
    }
    return dir;
  }
  const script = [...POSIX_SHIM_BODY, `BUN_BE_BUN=1 exec ${shellQuote(process.execPath)} "$@"`, ""].join("\n");
  writeIfChanged(join(dir, "node"), script, 0o755);
  return dir;
}

/** Environment PATH key, which is `Path` on some Windows setups. */
function pathKey(env: Record<string, string | undefined>): string {
  return Object.keys(env).find((key) => key.toUpperCase() === "PATH") ?? "PATH";
}

/**
 * Returns `env` with the node shim prepended to the PATH when `mode` asks
 * for it. `auto` looks for an existing `node` on the PATH of `env`.
 */
export function withNodeShim(env: Record<string, string | undefined>, mode: NodeShimMode = "auto"): Record<string, string | undefined> {
  if (mode === "never") return env;
  const key = pathKey(env);
  const current = env[key] ?? "";
  if (mode === "auto" && Bun.which("node", { PATH: current })) return env;
  const dir = ensureNodeShim();
  return { ...env, [key]: current ? `${dir}${delimiter}${current}` : dir };
}

/** Runs one embedded script and collects its output. */
export async function runScript(script: string, args: string[], options: RunOptions = {}): Promise<ScriptRun> {
  if (!(script in SKILL_FILES)) throw error.notFound(`Embedded script not found: ${script}`);
  const path = join(skillsRuntimeDir(), script);
  const child = Bun.spawn([process.execPath, path, ...args], {
    cwd: options.cwd ?? process.cwd(),
    env: withNodeShim({ ...process.env, ...options.env, BUN_BE_BUN: "1", NO_COLOR: "1" }, options.nodeShim),
    stdin: options.input === undefined ? "ignore" : new Blob([options.input]),
    stdout: "pipe",
    stderr: "pipe",
  });
  const [stdout, stderr, code] = await Promise.all([
    new Response(child.stdout).text(),
    new Response(child.stderr).text(),
    child.exited,
  ]);
  const run: ScriptRun = { script, args, code, stdout, stderr };
  const trimmed = stdout.trim();
  if (trimmed.startsWith("{") || trimmed.startsWith("[")) {
    try { run.json = JSON.parse(trimmed); } catch { /* plain text that starts with a brace */ }
  }
  return run;
}
